#!/usr/bin/env node

import { createReadStream } from 'node:fs';
import { stat } from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const DEFAULT_APP_DIR = path.join(ROOT, 'homey', 'app');
const require = createRequire(import.meta.url);
const AthomApi = require(path.join(DEFAULT_APP_DIR, 'node_modules', 'homey', 'services', 'AthomApi.js'));
const HomeyCliApp = require(path.join(DEFAULT_APP_DIR, 'node_modules', 'homey', 'lib', 'App.js'));

function parseArgs(argv) {
  const args = {
    appDir: 'homey/app',
  };

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--artifact') args.artifact = path.resolve(ROOT, argv[++i]);
    else if (arg === '--app-dir') args.appDir = argv[++i];
    else if (arg === '--clean') args.clean = true;
    else if (arg === '--help' || arg === '-h') args.help = true;
    else throw new Error(`Unknown argument: ${arg}`);
  }

  return args;
}

function printHelp() {
  console.log(`Usage:
  node tools/release/install-homey-app-artifact.mjs --artifact <file.tgz> [--app-dir homey/app-v2] [--clean]

Installs the exact Homey app tar.gz artifact generated by
tools/release/build-homey-app.mjs. This bypasses the Homey CLI install command's
preprocess step and sends the artifact stream directly to Homey Devkit.
`);
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help) {
    printHelp();
    return;
  }

  if (!args.artifact) {
    throw new Error('Missing required --artifact <file.tgz>');
  }

  const artifactStat = await stat(args.artifact);
  const homey = await AthomApi.getActiveHomey();
  if (homey.platform === 'cloud') {
    throw new Error('Installing apps is not available on Homey Cloud.');
  }

  const appDir = path.resolve(ROOT, args.appDir);
  const app = new HomeyCliApp(appDir);
  const env = await app._getEnv();

  console.log(`Installing exact Homey app artifact on ${homey.name}: ${path.relative(ROOT, args.artifact)} (${artifactStat.size} bytes)`);
  const result = await homey.devkit.runApp({
    app: createReadStream(args.artifact),
    env,
    clean: Boolean(args.clean),
  });

  console.log(`Homey App ${result.appId} successfully installed from artifact`);
}

main().catch(error => {
  console.error(error.stack || error.message);
  process.exit(1);
});
